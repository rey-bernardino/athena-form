#!/usr/bin/env node
// Write a rubric into src/config/scoring.config.js, the file the form imports.
//
// Only the rubric is generated (version, scale, tiers, forced tiers,
// questions). The operational switches - enabled, output fields, routing -
// stay hand-owned in src/config/form.config.js.
//
// Usage: node scoring/build-config.mjs [--rubric path] [--out path]

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.dirname(HERE);

function parseArgs(argv) {
  const spec = JSON.parse(fs.readFileSync(path.join(HERE, "spec.json"), "utf8"));
  const args = {
    rubric: path.join(HERE, "rubrics", `${spec.name}.json`),
    out: path.join(ROOT, "src", "config", "scoring.config.js"),
  };

  for (let i = 0; i < argv.length; i += 2) {
    args[argv[i].replace(/^--/, "")] = argv[i + 1];
  }

  return args;
}

const literal = (value) => JSON.stringify(value);
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : literal(name));
const comment = (text) => String(text).replaceAll("*/", "* /");

function block(entries, indent) {
  const pad = " ".repeat(indent);

  if (!entries.length) return "{}";

  return `{\n${entries.map(([name, value]) => `${pad}  ${key(name)}: ${literal(value)},`).join("\n")}\n${pad}}`;
}

function renderQuestion(question, labels) {
  const lines = [
    `    // ${comment(question.label)}`,
    "    {",
    `      id: ${literal(question.id)},`,
    `      source: ${literal(question.source)},`,
    `      field: ${literal(question.field)},`,
    `      maxPoints: ${question.maxPoints},`,
    `      aggregate: ${literal(question.aggregate)},`,
    `      defaultPoints: ${question.defaultPoints},`,
  ];

  if (Object.keys(question.aliases || {}).length) {
    lines.push(`      aliases: ${block(Object.entries(question.aliases), 6)},`);
  }

  const options = Object.entries(question.options).map(([option, points]) => {
    const label = labels.get(option);
    const note = label && label !== option ? ` // ${comment(label)}` : "";
    return `        ${key(option)}: ${points},${note}`;
  });

  lines.push(`      options: {\n${options.join("\n")}\n      },`, "    },");

  return lines.join("\n");
}

function render(rubric, rubricPath) {
  const labelsByField = new Map(
    rubric.diagnostics.map((question) => [
      question.field,
      new Map(question.options.map((option) => [option.key, option.label])),
    ])
  );

  const formKeyLabels = (question) => {
    const byKey = labelsByField.get(question.field) || new Map();
    return new Map(Object.keys(question.options).map((option) => [option, byKey.get(option.toLowerCase())]));
  };

  const tiers = rubric.tiers
    .map((tier) => `    { name: ${literal(tier.name)}, minScore: ${tier.minScore} },`)
    .join("\n");

  const forceTierRules = rubric.forceTierRules
    .map((rule) =>
      [
        "    {",
        `      id: ${literal(rule.id)},`,
        `      type: ${literal(rule.type)},`,
        `      field: ${literal(rule.field)},`,
        `      tier: ${literal(rule.tier)},`,
        `      domains: [\n${rule.domains.map((domain) => `        ${literal(domain)},`).join("\n")}\n      ],`,
        "    },",
      ].join("\n")
    )
    .join("\n");

  return `// src/config/scoring.config.js
//
// GENERATED by scoring/build-config.mjs from ${path.relative(ROOT, rubricPath)}.
// Do not edit by hand: change the rubric and run \`npm run scoring:config\`.
// The sign-off sheet for this rubric is scoring/reports/${rubric.name}.signoff.md.

export const SCORING_RUBRIC = {
  version: ${literal(rubric.name)},
  scale: ${literal(rubric.scale)},

  tiers: [
${tiers}
  ],

  forceTierRules: [
${forceTierRules}
  ],

  questions: [
${rubric.questions.map((question) => renderQuestion(question, formKeyLabels(question))).join("\n\n")}
  ],
};
`;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const rubric = JSON.parse(fs.readFileSync(args.rubric, "utf8"));

  fs.writeFileSync(args.out, render(rubric, args.rubric));
  console.log(`Wrote ${path.relative(ROOT, args.out)} (${rubric.name}, ${rubric.questions.length} questions)`);
}

main();
