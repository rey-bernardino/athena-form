// Sign-off sheet for Growth: what the rubric awards, where the tiers fall, and
// how it tested. One sentence per line, per the repo's Markdown convention.

const pct = (value, digits = 1) => (value === null || value === undefined ? "-" : `${(100 * value).toFixed(digits)}%`);
const num = (value) => (value ?? 0).toLocaleString("en-US");
const cell = (value) => String(value ?? "").replaceAll("|", "\\|");

const TIER_LABELS = { tier_1: "Tier 1", tier_2: "Tier 2", tier_3: "Tier 3" };

export function renderSignoff(evaluation) {
  const { spec, rubric, candidate, current, verdict, parity } = evaluation;
  const tier1 = rubric.tiers.find((tier) => tier.name === "tier_1").minScore;
  const tier2 = rubric.tiers.find((tier) => tier.name === "tier_2").minScore;
  const totalPoints = rubric.questions.reduce((sum, question) => sum + question.maxPoints, 0);
  const [testStart, testEnd] = spec.windows.test;
  const [baseStart, baseEnd] = spec.windows.baseline;

  const lines = [];
  const push = (...items) => lines.push(...items);

  push(
    `# Lead tier rubric ${rubric.name}: sign-off sheet`,
    "",
    `Generated by \`npm run scoring:report\` from \`scoring/rubrics/${rubric.name}.json\`.`,
    "Do not edit by hand; change the rubric and regenerate.",
    "",
    "## Summary",
    "",
    `Every new lead gets a score from 0 to 100 and a tier, computed in the form when it is submitted and sent to HubSpot as \`leadscoring_score\` and \`leadscoring_tier\`.`,
    `The goal is a tier 1 where at least ${spec.targets.tier1MinRate * 100}% of leads complete their close call.`,
    `On leads the rubric never saw (created ${testStart} to ${testEnd}), tier 1 completes at **${pct(candidate.test.tiers[0].rate)}** and holds ${pct(candidate.test.tiers[0].share, 0)} of leads, so it **${verdict.meetsTarget ? "meets" : "misses"}** the goal.`,
    `Ranking quality (AUC) is ${candidate.test.summary.auc.toFixed(3)}, against ${current.test.summary.auc.toFixed(3)} for the rubric that ran until October 9.`,
    `The top fifth of leads completes at ${pct(candidate.test.summary.topQuintile)} and the bottom fifth at ${pct(candidate.test.summary.bottomQuintile)}.`,
    "",
    "## Tiers",
    "",
    "| Tier | Score | Share of test leads | Close call completion | Completion, all leads |",
    "|---|---|---|---|---|"
  );

  const ranges = { tier_1: `${tier1}-100`, tier_2: `${tier2}-${tier1 - 1}`, tier_3: `0-${tier2 - 1}` };
  candidate.test.tiers.forEach((tier) => {
    push(`| ${TIER_LABELS[tier.tier]} | ${ranges[tier.tier]} | ${pct(tier.share, 0)} | ${pct(tier.rate)} | ${pct(tier.allLeads.rate)} |`);
  });

  push(
    "",
    `Leads whose email domain is on the blocked list (${spec.forceTierRules[0].domains.length} competitor and staffing domains) are always tier 3, as today.`,
    `"Close call completion" is among leads with a recorded call outcome; "all leads" also counts leads who never booked.`,
    "",
    "For comparison, the rubric that ran until October 9, on the same test leads:",
    "",
    "| Tier | Share of test leads | Close call completion |",
    "|---|---|---|"
  );

  current.test.tiers.forEach((tier) => {
    push(`| ${TIER_LABELS[tier.tier]} | ${pct(tier.share, 0)} | ${pct(tier.rate)} |`);
  });

  push(
    "",
    "## How the score works",
    "",
    "Each question has a cap: how much it adds to the ranking once every other question is known.",
    "Within a question, the answer with the weakest track record earns 0 and the strongest earns the full cap.",
    "On multi-select questions a lead earns their single best selected answer, so ticking every box does not inflate the score.",
    `The caps add up to ${totalPoints} points, and the score is the percentage of the available points a lead earned on the questions they were asked.`,
    "Answers with too little history earn the question's middle value until there is enough data to grade them.",
    "",
    "## Points per question",
    "",
    `Completion rates are from the baseline window (leads created ${baseStart} to ${baseEnd}).`,
    ""
  );

  [...rubric.diagnostics]
    .filter((question) => question.cap > 0)
    .sort((a, b) => b.cap - a.cap)
    .forEach((question) => {
      push(
        `### ${cell(question.label)} (cap ${question.cap}, ${pct(question.cap / totalPoints, 0)} of the score)`,
        "",
        "| Answer | Points | Completion | Baseline leads |",
        "|---|---|---|---|"
      );

      question.options.forEach((option) => {
        const label = option.kept ? cell(option.label) : `${cell(option.label)} (too few leads)`;
        push(`| ${label} | ${option.points} | ${pct(option.rate)} | ${num(option.n)} |`);
      });

      push(`| Any other answer | ${question.defaultPoints} | - | - |`, "");
    });

  push(
    "Not scored, because the answers do not separate outcomes once the other questions are known:",
    "",
    ...rubric.unscored.map((question) => `- ${question.label}`),
    "",
    "## Things to know before approving",
    "",
    "- Reps saw the old tier and calendar routing depended on it until October 9, so some of the historical differences come from how leads were treated rather than who they were.",
    "  Leads since October 9 saw no tier; re-running this report once they are 30 days old gives a cleaner read.",
    "- \"No UTM (direct / untracked)\" scores near the top of the traffic question.",
    "  A broken tracking tag would also land leads there.",
    "- Three newer questions were asked of only a few hundred leads in the baseline, so they carry small caps until more data accumulates.",
    `- The scoring code that produced these numbers is the code that runs in the form: replaying the old rubric through it reproduces ${num(parity.scoreMatches)} of ${num(parity.n)} stored scores exactly.`,
    "",
    "## Decisions needed",
    "",
    `- [ ] Approve the points per question above.`,
    `- [ ] Approve tier 1 at ${tier1}+ and tier 3 below ${tier2}.`,
    `- [ ] Confirm which tiers skip the calendar when scoring is turned on (today: ${spec.routing.skipCalendarTiers.map((tier) => TIER_LABELS[tier]).join(", ") || "none"}).`,
    ""
  );

  return lines.join("\n");
}
